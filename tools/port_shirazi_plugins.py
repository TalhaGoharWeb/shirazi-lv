#!/usr/bin/env python3
"""Port Shirazi plugins into Mark-LV's plugin contract.

Reads each shirazi-core/plugins/<name>/ (plugin.yaml + plugin.py with TOOLS)
and generates one Mark-LV plugin file per Shirazi TOOL at
<shirazi-lv>/plugins/shirazi_<tool>.py:

  PLUGIN = {name, description, parameters}   # Mark-LV contract
  run(parameters, player=None, session_memory=None) -> str

Notes:
- Shirazi parameter types are lowercase ("object"); Mark-LV requires UPPERCASE
  ("OBJECT") — normalized here.
- Shirazi permission declarations have no Mark-LV equivalent; they are
  surfaced in the tool description so the model/user can see them.
- Tool names are prefixed `shirazi_` to avoid collisions with Mark-LV's own
  actions/plugins.
- The Shirazi plugin module is loaded from its file path via importlib; only
  stdlib imports are used by the plugins, so this is self-contained.

Usage: python3 tools/port_shirazi_plugins.py
"""
from __future__ import annotations

import importlib.util
import sys
from pathlib import Path

SHIRAZI_PLUGINS = Path(__file__).resolve().parent.parent / "vendor" / "shirazi" / "plugins"
OUT_DIR = Path(__file__).resolve().parent.parent / "plugins"

# Plugins with a REAL settings form. The wrapper reads these via
# get_plugin_config(namespace) and honors them in run() (currently by
# setting env vars the vendored tool reads). Only entries where the setting
# genuinely changes behavior -- no decorative settings.
PLUGIN_SETTINGS_MAP = {
    "excel_writer": {
        "namespace": "shirazi_excel",
        "title": "Excel Writer",
        "fields": [
            {"key": "save_folder", "type": "text",
             "label": "Save folder",
             "default": "",
             "description": "Where .xlsx files are saved. Empty = Desktop."},
        ],
        "env": {"save_folder": "SHIRAZI_EXCEL_DIR"},
    },
}

_TYPE_UP = {
    "object": "OBJECT", "string": "STRING", "number": "NUMBER",
    "integer": "INTEGER", "boolean": "BOOLEAN", "array": "ARRAY",
    "null": "NULL",
}


def _norm_types(node):
    if isinstance(node, dict):
        out = {}
        for k, v in node.items():
            if k == "type" and isinstance(v, str):
                out[k] = _TYPE_UP.get(v.lower(), v)
            else:
                out[k] = _norm_types(v)
        # Gemini Live rejects ARRAY schemas whose items lack a type.
        if out.get("type") == "ARRAY":
            items = out.get("items")
            if not isinstance(items, dict) or "type" not in items:
                out["items"] = {"type": "STRING"}
        # Gemini Live rejects empty strings inside enums.
        if isinstance(out.get("enum"), list):
            out["enum"] = [e for e in out["enum"] if e != ""]
        return out
    if isinstance(node, list):
        return [_norm_types(x) for x in node]
    return node


def _load_plugin_module(plugin_dir: Path):
    """Load a Shirazi plugin.py + plugin.yaml without importing shirazi-core."""
    pf = plugin_dir / "plugin.py"
    spec = importlib.util.spec_from_file_location(
        f"_shirazi_port_{plugin_dir.name}", pf)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    meta = {"name": plugin_dir.name, "version": "?", "description": "",
            "permissions": []}
    yf = plugin_dir / "plugin.yaml"
    if yf.exists():
        for line in yf.read_text(encoding="utf-8").splitlines():
            if ":" not in line or line.startswith(" "):
                continue
            k, v = line.split(":", 1)
            k, v = k.strip(), v.strip()
            if k == "permissions":
                v = v.strip("[]")
                meta["permissions"] = [x.strip() for x in v.split(",") if x.strip()]
            elif k in meta:
                meta[k] = v
    return mod, meta


TEMPLATE = '''"""{doc}
Auto-generated by tools/port_shirazi_plugins.py — do not hand-edit.
Source: shirazi-assistant/shirazi-core/plugins/{plugin}/plugin.py (v{version})
Upstream: https://github.com/TalhaGoharWeb/shirazi-personal-assistant
Shirazi-origin; integrated into Shirazi LV under the project's attribution terms.
"""
from __future__ import annotations

import importlib.util
from pathlib import Path

_PLUGIN_FILE = (Path(__file__).resolve().parent.parent / "vendor" / "shirazi"
                  / "plugins" / {plugindir!r} / "plugin.py")


def _load_tool():
    # All generated files from the SAME Shirazi plugin share one loaded module
    # instance (keyed in sys.modules), so stateful plugins (timer, notes,
    # task_recovery, ...) behave as one plugin, not N independent copies.
    import sys
    _KEY = "_shirazi_shared_{plugin}"
    mod = sys.modules.get(_KEY)
    if mod is None:
        spec = importlib.util.spec_from_file_location(_KEY, _PLUGIN_FILE)
        mod = importlib.util.module_from_spec(spec)
        sys.modules[_KEY] = mod
        spec.loader.exec_module(mod)
    for t in mod.TOOLS:
        if t.get("name") == {tool!r}:
            return t["run"]
    raise RuntimeError("tool {tool!r} not found in Shirazi plugin")


_RUN = _load_tool()

PLUGIN = {{
    "name": {pname!r},
    "description": {desc!r},
    "parameters": {params!r},
}}

PLUGIN_SETTINGS = {psettings!r}


def _apply_settings():
    """Push saved settings into the environment the vendored tool reads.
    Runs on every call so a changed setting takes effect without restart."""
    if not PLUGIN_SETTINGS:
        return
    try:
        from memory.config_manager import get_plugin_config
        ns = PLUGIN_SETTINGS.get("namespace") or {pname!r}
        values = get_plugin_config(ns) or {{}}
        import os
        for key, var in (PLUGIN_SETTINGS.get("env") or {{}}).items():
            val = str(values.get(key) or "").strip()
            if val:
                os.environ[var] = val
            else:
                os.environ.pop(var, None)
    except Exception:
        pass


def run(parameters: dict, player=None, session_memory=None) -> str:
    """Mark-LV plugin contract: never raise; return a spoken string."""
    try:
        _apply_settings()
        return str(_RUN(dict(parameters or {{}})))
    except Exception as e:
        return f"Shirazi tool '{pname}' failed: {{e}}"
'''


def main() -> int:
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    count, skipped = 0, []
    for pdir in sorted(SHIRAZI_PLUGINS.iterdir()):
        if not pdir.is_dir() or not (pdir / "plugin.py").exists():
            continue
        if pdir.name.startswith("_"):
            continue  # _template etc. are not real plugins
        try:
            mod, meta = _load_plugin_module(pdir)
        except Exception as e:
            skipped.append((pdir.name, f"load: {e}"))
            continue
        tools = getattr(mod, "TOOLS", None)
        if not tools:
            skipped.append((pdir.name, "no TOOLS"))
            continue
        for tool in tools:
            tname = tool.get("name", "")
            if not tname:
                skipped.append((pdir.name, "tool without name"))
                continue
            pname = f"shirazi_{tname}"
            params = _norm_types(tool.get("parameters") or {})
            if not isinstance(params, dict) or params.get("type") != "OBJECT":
                params = {"type": "OBJECT", "properties": {}}
            desc = tool.get("description", "") or tname
            perms = meta["permissions"]
            if perms:
                desc = f"{desc} [shirazi permissions: {', '.join(perms)}]"
            doc = f"Shirazi-origin tool: {{tname}} (plugin '{{meta['name']}}'). {{desc}}"
            code = TEMPLATE.format(
                doc=doc, plugin=pdir.name, version=meta["version"],
                plugindir=pdir.name, tool=tname,
                pname=pname, desc=desc, params=params,
                psettings=PLUGIN_SETTINGS_MAP.get(pdir.name))
            (OUT_DIR / f"{pname}.py").write_text(code, encoding="utf-8")
            count += 1
    print(f"generated {count} plugin files")
    for name, why in skipped:
        print(f"  skipped {name}: {why}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
